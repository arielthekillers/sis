<?php

namespace App\Database\Seeds;

use CodeIgniter\Database\Seeder;

class DataAwalSeeder extends Seeder
{
    public function run()
    {
        require ROOTPATH . 'seeder_data.php';

        // 1. Tahun Ajaran
        $this->db->table('tahun_ajaran')->insert([
            'tahun' => '2026/2027',
            'is_active' => 1,
            'created_at' => date('Y-m-d H:i:s'),
            'updated_at' => date('Y-m-d H:i:s')
        ]);
        $taId = '2026/2027';

        // 2. Guru
        $guruIds = [];
        $semuaGuru = [];
        foreach ($classes as $kelas => $walis) {
            foreach ($walis as $wali) {
                $cleanName = trim(str_ireplace('MISS ', '', $wali));
                if (!in_array($cleanName, $semuaGuru)) {
                    $semuaGuru[] = $cleanName;
                    $this->db->table('guru_staf')->insert([
                        'nama_lengkap' => $cleanName,
                        'nama_panggilan' => $cleanName,
                        'sapaan' => 'Miss',
                        'nip' => 'G' . rand(1000, 9999),
                        'jenis_kelamin' => 'P',
                        'status_pegawai' => 'Tetap',
                        'created_at' => date('Y-m-d H:i:s'),
                        'updated_at' => date('Y-m-d H:i:s')
                    ]);
                    $guruIds[$wali] = $this->db->insertID();
                } else {
                    // Find the ID if already inserted (in case multiple classes share a teacher)
                    $row = $this->db->table('guru_staf')->where('nama_lengkap', $cleanName)->get()->getRow();
                    if($row) $guruIds[$wali] = $row->id;
                }
            }
        }

        // 3. Kelas (Rombel)
        $kelasIds = [];
        foreach ($classes as $namaKelas => $walis) {
            $rawTingkat = explode(' ', $namaKelas)[0];
            
            $tingkat = '';
            $finalNamaKelas = $namaKelas;
            if ($rawTingkat == 'TODDLER') {
                $tingkat = 'BT';
            } elseif ($rawTingkat == 'PLAYGROUP') {
                $tingkat = 'KB';
            } elseif ($rawTingkat == 'KG-A') {
                $tingkat = 'TK';
                $finalNamaKelas = 'Kinder A';
            } elseif (strpos($rawTingkat, 'KG-B') !== false || strpos($namaKelas, 'KG-B') !== false) {
                $tingkat = 'TK';
                if (strpos($namaKelas, '1') !== false) {
                    $finalNamaKelas = 'Kinder B1';
                } elseif (strpos($namaKelas, '2') !== false) {
                    $finalNamaKelas = 'Kinder B2';
                } else {
                    $finalNamaKelas = 'Kinder B';
                }
            }
            
            $waliIds = [];
            foreach ($walis as $wali) {
                if(isset($guruIds[$wali])) {
                    $waliIds[] = $guruIds[$wali];
                }
            }
            
            $this->db->table('kelas')->insert([
                'tahun_ajaran' => $taId,
                'tingkat' => $tingkat,
                'nama_kelas' => $finalNamaKelas,
                'wali_kelas' => json_encode($waliIds),
                'keterangan' => 'Generated by seeder',
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ]);
            $kelasIds[$namaKelas] = $this->db->insertID();
        }

        // 4. Siswa & Anggota Rombel
        foreach ($students as $i => $s) {
            // Siswa
            $nis = 'S' . str_pad($i + 1, 4, '0', STR_PAD_LEFT);
            $this->db->table('siswa')->insert([
                'nis' => $nis,
                'nama_lengkap' => $s['nama'],
                'tanggal_lahir' => $s['tanggal_lahir'],
                'jenis_kelamin' => 'L', // dummy default
                'status_siswa' => 'Aktif',
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ]);
            $siswaId = $this->db->insertID();

            // Anggota Rombel
            if (isset($kelasIds[$s['kelas']])) {
                $this->db->table('rombel_siswa')->insert([
                    'rombel_id' => $kelasIds[$s['kelas']],
                    'siswa_id' => $siswaId,
                    'created_at' => date('Y-m-d H:i:s')
                ]);
            }
        }

        // 5. Keuangan (Master)
        $this->db->table('keu_jenis_pembayaran')->insertBatch([
            [
                'nama_pembayaran' => 'SPP Reguler',
                'nominal' => 500000,
                'tipe_siklus' => 'Bulanan',
                'is_active' => 1,
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ],
            [
                'nama_pembayaran' => 'SPP Halfday',
                'nominal' => 300000,
                'tipe_siklus' => 'Bulanan',
                'is_active' => 1,
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ],
            [
                'nama_pembayaran' => 'Katering/Makan Siang',
                'nominal' => 200000,
                'tipe_siklus' => 'Bulanan',
                'is_active' => 1,
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ],
            [
                'nama_pembayaran' => 'Uang Gedung',
                'nominal' => 2500000,
                'tipe_siklus' => 'Sekali Bayar',
                'is_active' => 1,
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ]
        ]);
    }
}
